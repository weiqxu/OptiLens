const {chromium,expect}=require('@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');

(async()=>{
  const browser=await chromium.launch({headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('400 (Bad Request)'))errors.push(m.text());});
    await page.goto(process.env.OPTILENS_TEST_URL||'http://127.0.0.1:8080');
    await expect(page.locator('#run')).toBeEnabled();
    await expect(page.locator('#database')).toHaveValue('calcite');
    assert.equal(await page.locator('#database option').count(),1);
    assert.ok(await page.locator('#rule-options input').count()>200);
    await expect(page.locator('#rule-count')).toContainText('已选 5');
    await page.fill('#rule-search','PROJECT_REDUCE_EXPRESSIONS');
    await expect(page.locator('.rule-row:visible')).toHaveCount(1);
    await expect(page.locator('#rule-count')).toContainText('已选 5');
    await page.fill('#rule-search','');
    await page.selectOption('#rule-category','Enumerable 物理规则');
    await expect(page.locator('.rule-row:visible input').first()).toBeDisabled();
    await page.selectOption('#rule-category','');
    await page.click('#run');
    await expect(page.locator('#status')).toHaveText(/^已完成/,{timeout:40000});
    assert.ok(await page.locator('.plan-node').count()>0);
    await page.getByRole('button',{name:/2 · 连接谓词下推/}).click();
    assert.match(await page.locator('#scope').textContent(),/阶段边界/);
    await page.locator('#steps .event-button').first().click();
    assert.match(await page.locator('#scope').textContent(),/局部表达式/);
    await page.locator('#after .plan-node').first().click();
    assert.equal(await page.locator('#node-details').getAttribute('open'),'');
    assert.match(await page.locator('#node-content').textContent(),/attributes/);
    await page.locator('[data-zoom="after:1"]').click();
    await page.getByRole('button',{name:'初始 → 最终',exact:false}).click();
    if(process.env.OPTILENS_SCREENSHOT_DIR){await fs.mkdir(process.env.OPTILENS_SCREENSHOT_DIR,{recursive:true});await page.screenshot({path:path.join(process.env.OPTILENS_SCREENSHOT_DIR,'desktop.png'),fullPage:true});}
    const downloadPromise=page.waitForEvent('download');await page.click('#export');const download=await downloadPromise;
    const file=await download.path();const exported=JSON.parse(await fs.readFile(file,'utf8'));assert.equal(exported.engine,'Apache Calcite');
    await page.setInputFiles('#import-file',file);
    await expect(page.locator('#status')).toHaveText(/^已导入/,{timeout:10000});
    assert.match(await page.locator('#provenance').textContent(),/未重新执行/);
    await page.fill('#sql','SELECT missing FROM customers');await page.click('#run');
    await expect(page.locator('#status')).toHaveClass(/error/,{timeout:40000});
    assert.match(await page.locator('#status').textContent(),/missing/i);
    await page.selectOption('#examples','identity');
    await page.click('#rule-clear');
    await page.click('#run');await expect(page.locator('#status')).toHaveText(/^已完成/,{timeout:40000});
    assert.match(await page.locator('#change-title').textContent(),/未观察到/);
    await page.selectOption('#examples','constant');await page.click('#rule-clear');
    await page.fill('#rule-search','PROJECT_REDUCE_EXPRESSIONS');
    await page.locator('input[value="CoreRules.PROJECT_REDUCE_EXPRESSIONS"]').check();
    await page.fill('#rule-search','no_such_rule_xyz');
    await expect(page.locator('#rule-empty')).toBeVisible();
    await expect(page.locator('#rule-count')).toContainText('已选 1');
    await page.click('#run');await expect(page.locator('#status')).toHaveText(/^已完成/,{timeout:40000});
    assert.match(await page.locator('#raw-after').textContent(),/200/);
    const single=await (await page.request.get(new URL(await page.locator('#export').getAttribute('href'),page.url()).href)).json();
    assert.equal(single.input.database,'calcite');assert.deepEqual(single.input.rules,['CoreRules.PROJECT_REDUCE_EXPRESSIONS']);
    await page.fill('#rule-search','');
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Page should fit mobile viewport');
    await page.locator('#after .plan-node').first().focus();await page.keyboard.press('Enter');
    assert.equal(await page.locator('#node-details').getAttribute('open'),'');
    if(process.env.OPTILENS_SCREENSHOT_DIR)await page.screenshot({path:path.join(process.env.OPTILENS_SCREENSHOT_DIR,'mobile.png'),fullPage:true});
    assert.deepEqual(errors,[],'No JavaScript or CSP errors');
    console.log('Browser checks passed: database selector, catalog search/filter, individual rule execution, real run, stage/event selection, node details, zoom, export/import, SQL error, empty rule program, keyboard interaction, mobile layout.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
